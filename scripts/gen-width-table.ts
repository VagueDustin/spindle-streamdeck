// Dev-only generator for src/render/widths.generated.ts. Run with `npm run gen:widths`.
// Reads Segoe UI advance widths from the machine's installed fonts and writes numeric metrics only
// (no glyph data). Kerning is deliberately ignored.
import type * as OpenType from "opentype.js";
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";

// opentype.js ships a UMD bundle whose named exports Node cannot detect from ESM, so load it via require.
const { parse } = createRequire(import.meta.url)("opentype.js") as typeof OpenType;

const FONTS = {
	400: "segoeui.ttf",
	600: "seguisb.ttf",
	700: "segoeuib.ttf"
} as const;
type Weight = keyof typeof FONTS;

const fontDir = "C:\\Windows\\Fonts";
const outFile = path.resolve(import.meta.dirname, "..", "src", "render", "widths.generated.ts");

/** Basic Latin through Latin Extended-B, then general punctuation dashes and quotes. */
const RANGES: ReadonlyArray<readonly [number, number]> = [
	[0x0020, 0x024f],
	[0x2010, 0x203a]
];

const round4 = (n: number): number => Math.round(n * 10000) / 10000;

function load(file: string) {
	const buf = fs.readFileSync(path.join(fontDir, file));
	return parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
}

const tables: Record<number, Record<number, number>> = {};
const fallback: Record<number, number> = {};

for (const weight of Object.keys(FONTS).map(Number) as Weight[]) {
	const font = load(FONTS[weight]);
	const em = font.unitsPerEm;
	const table: Record<number, number> = {};
	for (const [lo, hi] of RANGES) {
		for (let cp = lo; cp <= hi; cp++) {
			const ch = String.fromCodePoint(cp);
			// Index 0 is .notdef: the font has no glyph for this code point, so leave it to the fallback.
			if (font.charToGlyphIndex(ch) === 0) continue;
			const adv = font.charToGlyph(ch).advanceWidth;
			if (adv === undefined) continue;
			table[cp] = round4(adv / em);
		}
	}
	tables[weight] = table;
	let sum = 0;
	for (let cp = 0x61; cp <= 0x7a; cp++) sum += table[cp];
	fallback[weight] = round4(sum / 26);
}

const body = (Object.keys(FONTS) as string[])
	.map((w) => {
		const entries = Object.entries(tables[Number(w)])
			.map(([cp, em]) => `${cp}:${em}`)
			.join(",");
		return `\t${w}: {${entries}}`;
	})
	.join(",\n");

const out = `// Generated by scripts/gen-width-table.ts (npm run gen:widths). Do not edit by hand.
// Source fonts: Segoe UI Regular (segoeui.ttf, 400), Segoe UI Semibold (seguisb.ttf, 600) and
// Segoe UI Bold (segoeuib.ttf, 700), read from the Windows Fonts folder.
// Contains only numeric horizontal advance widths in em units (advance / unitsPerEm, 4 dp),
// keyed by code point, for U+0020-U+024F and U+2010-U+203A. Kerning is not included.

export const WIDTHS: Record<400 | 600 | 700, Record<number, number>> = {
${body}
};

/** Mean advance of a-z per weight, used for code points missing from the table. */
export const FALLBACK_EM: Record<400 | 600 | 700, number> = {
	400: ${fallback[400]},
	600: ${fallback[600]},
	700: ${fallback[700]}
};
`;

fs.writeFileSync(outFile, out);
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${out.length} bytes)`);
